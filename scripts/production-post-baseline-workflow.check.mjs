import {test} from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const workflow=readFileSync('/work/cd.yml','utf8'),transport=readFileSync('/work/scripts/staging-transport.sh','utf8'),preflight=readFileSync('/work/scripts/production-post-baseline-preflight.sh','utf8')
test('rotas manual e automática usam ambiente protegido e origem composta',()=>{assert.match(workflow,/workflow_run:/);assert.match(workflow,/workflow_dispatch:/);assert.match(workflow,/environment: production/);assert.match(workflow,/production-post-baseline-source\.mjs select/);assert.match(workflow,/\.fixture == false and \.operationalReady == false/);assert.match(workflow,/production-post-baseline "\$STAGING_RUN" "\$STAGING_IMAGE"/);assert.match(workflow,/production-initial "\$STAGING_RUN"/)})
test('transporte posterior consulta preflight sem incoming, fetch, load ou checkout',()=>{const part=transport.split('if [[ "$mode" == production-post-baseline ]]; then')[1].split("remote='set -euo pipefail")[0];assert.match(part,/production-post-baseline-preflight\.sh/);assert.match(part,/exec 9<>/);assert.match(part,/flock -n 9/);assert.match(part,/<\/dev\/null/);assert.doesNotMatch(part,/git fetch|docker (?:load|run|create)|git checkout|incoming_dir/);assert.match(preflight,/exit 78/);assert.doesNotMatch(preflight,/docker (?:load|run|create|start|stop)|git checkout/)})
test('pré-clientes usa environment protegido e só finaliza após atestar e publicar receipt',()=>{
 assert.match(workflow,/environment: production/)
 assert.match(workflow,/workflow_run:/);assert.match(workflow,/workflow_dispatch:/)
 const apply=workflow.indexOf('name: Promove mesmo artefato em modo pré-clientes')
 const attest=workflow.indexOf('name: Atesta recibo de produção')
 const upload=workflow.indexOf('name: Publica recibo de produção')
 const finalize=workflow.indexOf('name: Conclui pending após publicação do recibo')
 assert.ok(apply>0 && apply<attest && attest<upload && upload<finalize)
 assert.match(workflow.slice(apply,attest),/production-preclients/)
 assert.match(workflow.slice(apply,attest),/applied_pending_finalization/)
 assert.match(workflow.slice(finalize),/production-preclients-finalize/)
 assert.doesNotMatch(workflow.slice(finalize),/always\s*\(/)
 assert.match(workflow,/production-post-baseline-source\.mjs select/)
})
test('CD recorrente mantém ambiente, mesma seleção nos dois eventos e finalização após upload',()=>{
 assert.match(workflow,/environment: production/)
 assert.match(workflow,/STAGING_RUN: \$\{\{ inputs\.staging_run \|\| github\.event\.workflow_run\.id \}\}/)
 assert.match(workflow,/secrets\.VPS_PRODUCTION_RECURRING_KEY/)
 const apply=workflow.indexOf('name: Verifica origem e promove pelo controlador recorrente')
 const attest=workflow.indexOf('name: Atesta recibo de produção')
 const upload=workflow.indexOf('name: Publica recibo de produção')
 const finalize=workflow.indexOf('name: Finaliza transação recorrente após atestar e publicar')
 assert.ok(apply>0&&apply<attest&&attest<upload&&upload<finalize)
 assert.match(workflow.slice(apply,attest),/node scripts\/recurring-runner\.mjs production/)
 assert.match(workflow.slice(finalize),/node scripts\/recurring-runner\.mjs finalize/)
 assert.doesNotMatch(workflow.slice(finalize),/always\s*\(/)
 assert.match(workflow,/CT011_PRODUCTION_MODE != 'production-recurring'/)
})

test('staging recorrente usa controlador fixado e atesta somente após execução validada',()=>{
 const stage=readFileSync('/work/staging.yml','utf8')
 assert.match(stage,/environment: staging/)
 assert.match(stage,/cancel-in-progress: false/)
 assert.match(stage,/ref: \$\{\{ vars\.CT011_CONTROLLER_SHA \}\}/)
 assert.match(stage,/secrets\.VPS_STAGING_RECURRING_KEY/)
 const execute=stage.indexOf('name: Verifica origem e envia pelo controlador recorrente')
 const attest=stage.indexOf('name: Atesta recibo do staging')
 const upload=stage.indexOf('name: Publica recibo de staging')
 assert.ok(execute>0&&execute<attest&&attest<upload)
 assert.match(stage.slice(execute,attest),/node scripts\/recurring-runner\.mjs staging/)
 assert.doesNotMatch(stage.slice(attest),/always\s*\(/)
})
